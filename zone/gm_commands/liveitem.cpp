void command_itemforge(Client *c, const Seperator *sep)
{
	if (!LiveItemsEnabled()) {
		c->Message(Chat::White, "Live Items are disabled on this server.");
		return;
	}

	const auto arguments = sep->argnum;
	if (!arguments || !strcasecmp(sep->arg[1], "help")) {
		SendItemForgeUsage(c);
		return;
	}

	const bool is_dialog = !strcasecmp(sep->arg[1], "dialog") || !strcasecmp(sep->arg[1], "open");
	const bool is_craft = !strcasecmp(sep->arg[1], "craft") || !strcasecmp(sep->arg[1], "create");
	const bool is_draft = !strcasecmp(sep->arg[1], "draft") || !strcasecmp(sep->arg[1], "begin");
	const bool is_set = !strcasecmp(sep->arg[1], "set");
	const bool is_finish = !strcasecmp(sep->arg[1], "finish");
	const bool is_reset = !strcasecmp(sep->arg[1], "reset");

	if (is_dialog) {
		c->Message(Chat::White, "Opening the Item Forge.");
		c->Message(
			Chat::White,
			fmt::format(
				"LIVEITEM|ui|open|types=weapon,armor,jewelry,charm,shield,augment|max_hp=500|max_mana=500|max_ac=100|max_damage=100|max_haste=50|stats={}",
				ItemForgeStatPayload()
			).c_str()
		);
		return;
	}

	if (is_draft) {
		auto values = ParseItemForgeDraft("");
		for (int index = 2; index <= sep->argnum; ++index) {
			std::string key;
			std::string value;
			if (ParseItemForgeToken(sep->arg[index], key, value)) {
				if (key == "name") {
					value = SanitizeItemForgeName(value);
				}
				SetItemForgeDraftValue(values, key, value);
			}
		}

		if (GetItemForgeDraftValue(values, "type").empty()) {
			SetItemForgeDraftValue(values, "type", "weapon");
		}

		if (GetItemForgeDraftValue(values, "name").empty()) {
			SetItemForgeDraftValue(values, "name", "Forged_Item");
		}

		DataBucket::SetData(&database, ItemForgeDraftBucketKey(c), BuildItemForgeDraft(values), "60");
		c->Message(Chat::White, "Item Forge draft started.");
		return;
	}

	if (is_set) {
		if (arguments < 2) {
			c->Message(Chat::White, "Usage: #itemforge set hp=50");
			return;
		}

		auto values = ParseItemForgeDraft(DataBucket::GetData(&database, ItemForgeDraftBucketKey(c)));
		if (values.empty()) {
			SetItemForgeDraftValue(values, "type", "weapon");
			SetItemForgeDraftValue(values, "name", "Forged_Item");
		}

		std::string key;
		std::string value;
		if (!ParseItemForgeToken(sep->arg[2], key, value)) {
			c->Message(Chat::White, "Usage: #itemforge set hp=50");
			return;
		}

		if (key == "name") {
			value = SanitizeItemForgeName(value);
		}

		SetItemForgeDraftValue(values, key, value);
		DataBucket::SetData(&database, ItemForgeDraftBucketKey(c), BuildItemForgeDraft(values), "60");
		return;
	}

	if (is_finish) {
		const auto draft_key = ItemForgeDraftBucketKey(c);
		auto values = ParseItemForgeDraft(DataBucket::GetData(&database, draft_key));
		if (values.empty()) {
			c->Message(Chat::White, "No Item Forge draft is active. Reopen the forge and try again.");
			return;
		}

		ItemForgeDefinition definition;
		const auto item_type = GetItemForgeDraftValue(values, "type");
		const auto name = GetItemForgeDraftValue(values, "name");
		if (!item_type.empty()) {
			definition.item_type = item_type;
		}

		if (!name.empty()) {
			definition.name = name;
		}

		definition.hp = GetItemForgeDraftInt(values, "hp", definition.hp);
		definition.mana = GetItemForgeDraftInt(values, "mana", definition.mana);
		definition.ac = GetItemForgeDraftInt(values, "ac", definition.ac);
		definition.damage = GetItemForgeDraftInt(values, "damage", definition.damage);
		definition.delay = GetItemForgeDraftInt(values, "delay", definition.delay);
		definition.haste = GetItemForgeDraftInt(values, "haste", definition.haste);

		CreateForgedLiveItem(c, definition, nullptr, &values);
		DataBucket::DeleteData(&database, draft_key);
		return;
	}

	if (is_reset) {
		DataBucket::DeleteData(&database, ItemForgeDraftBucketKey(c));
		c->Message(Chat::White, "Item Forge draft cleared.");
		return;
	}

	if (!is_craft) {
		SendItemForgeUsage(c);
		return;
	}

	ItemForgeDefinition definition;
	if (HasItemForgeNamedArgs(sep)) {
		const auto item_type = GetItemForgeNamedArg(sep, "type");
		const auto name = GetItemForgeNamedArg(sep, "name");
		if (!item_type.empty()) {
			definition.item_type = item_type;
		}

		if (!name.empty()) {
			definition.name = name;
		}

		definition.hp = GetItemForgeNamedInt(sep, "hp", definition.hp);
		definition.mana = GetItemForgeNamedInt(sep, "mana", definition.mana);
		definition.ac = GetItemForgeNamedInt(sep, "ac", definition.ac);
		definition.damage = GetItemForgeNamedInt(sep, "damage", definition.damage);
		definition.delay = GetItemForgeNamedInt(sep, "delay", definition.delay);
		definition.haste = GetItemForgeNamedInt(sep, "haste", definition.haste);
	} else {
		definition.item_type = arguments >= 2 ? std::string(sep->arg[2]) : definition.item_type;
		definition.hp = (arguments >= 3 && sep->IsNumber(3)) ? Strings::ToInt(sep->arg[3]) : definition.hp;
		definition.mana = (arguments >= 4 && sep->IsNumber(4)) ? Strings::ToInt(sep->arg[4]) : definition.mana;
		definition.ac = (arguments >= 5 && sep->IsNumber(5)) ? Strings::ToInt(sep->arg[5]) : definition.ac;
		definition.damage = (arguments >= 6 && sep->IsNumber(6)) ? Strings::ToInt(sep->arg[6]) : definition.damage;
		definition.delay = (arguments >= 7 && sep->IsNumber(7)) ? Strings::ToInt(sep->arg[7]) : definition.delay;
		definition.haste = (arguments >= 8 && sep->IsNumber(8)) ? Strings::ToInt(sep->arg[8]) : definition.haste;
	}

	CreateForgedLiveItem(c, definition, sep);
}

void command_liveitem(Client *c, const Seperator *sep)
{
	if (!LiveItemsEnabled()) {
		c->Message(Chat::White, "Live Items are disabled on this server.");
		return;
	}

	const auto arguments = sep->argnum;
	if (!arguments || !strcasecmp(sep->arg[1], "help")) {
		SendLiveItemUsage(c);
		return;
	}

	const bool is_status = !strcasecmp(sep->arg[1], "status");
	const bool is_clear  = !strcasecmp(sep->arg[1], "clear");
	const bool is_clone  = !strcasecmp(sep->arg[1], "clone");
	const bool is_summon = !strcasecmp(sep->arg[1], "summon");
	const bool is_bump   = !strcasecmp(sep->arg[1], "bump");

	if (!is_status && !is_clear && !is_clone && !is_summon && !is_bump) {
		SendLiveItemUsage(c);
		return;
	}

	if (is_clear) {
		if (arguments < 2 || !strcasecmp(sep->arg[2], "all")) {
			database.ClearLiveItemCache();
			c->Message(Chat::White, "Cleared all live item cache entries.");
			return;
		}

		if (!sep->IsNumber(2)) {
			SendLiveItemUsage(c);
			return;
		}

		const auto item_id = Strings::ToUnsignedInt(sep->arg[2]);
		if (!IsValidLiveItemID(c, item_id)) {
			return;
		}

		c->Message(
			Chat::White,
			fmt::format(
				"Live item cache entry for item ID {} {}.",
				item_id,
				database.ClearLiveItemCache(item_id) ? "cleared" : "was not cached"
			).c_str()
		);
		return;
	}

	if (is_status) {
		if (arguments < 2 || !sep->IsNumber(2)) {
			SendLiveItemUsage(c);
			return;
		}

		const auto item_id = Strings::ToUnsignedInt(sep->arg[2]);
		if (!IsValidLiveItemID(c, item_id)) {
			return;
		}

		const bool eligible = database.IsLiveItemID(item_id);
		c->Message(Chat::White, fmt::format("Live Item ID [{}]: {}", item_id, eligible ? "eligible" : "not eligible").c_str());

		const auto *item = database.GetItem(item_id);
		SendItemSummary(c, item);

		SharedDatabase::LiveItemCacheEntry entry {};
		if (database.GetLiveItemCacheEntry(item_id, entry)) {
			c->Message(
				Chat::White,
				fmt::format(
					"Cache: exists [{}] last_checked [{}] updated [{}]",
					entry.exists ? "true" : "false",
					entry.last_checked,
					entry.updated
				).c_str()
			);
		} else {
			c->Message(Chat::White, "Cache: no entry.");
		}
		return;
	}

	if (is_clone) {
		if (arguments < 3 || !sep->IsNumber(2) || !sep->IsNumber(3)) {
			SendLiveItemUsage(c);
			return;
		}

		const auto target_id = Strings::ToUnsignedInt(sep->arg[2]);
		const auto source_id = Strings::ToUnsignedInt(sep->arg[3]);
		if (!IsValidLiveItemID(c, target_id) || !IsValidLiveItemID(c, source_id)) {
			return;
		}

		if (!database.IsLiveItemID(target_id)) {
			c->Message(Chat::White, fmt::format("Item ID {} is outside the configured live item range.", target_id).c_str());
			return;
		}

		if (UpsertLiveItemClone(c, target_id, source_id)) {
			SummonLiveItem(c, target_id, 1);
		}
		return;
	}

	if (is_summon) {
		if (arguments < 2 || !sep->IsNumber(2)) {
			SendLiveItemUsage(c);
			return;
		}

		const auto item_id = Strings::ToUnsignedInt(sep->arg[2]);
		if (!IsValidLiveItemID(c, item_id)) {
			return;
		}

		const int16 charges = (arguments >= 3 && sep->IsNumber(3)) ? static_cast<int16>(Strings::ToInt(sep->arg[3])) : -1;
		SummonLiveItem(c, item_id, charges);
		return;
	}

	if (is_bump) {
		if (arguments < 2 || !sep->IsNumber(2)) {
			SendLiveItemUsage(c);
			return;
		}

		const auto item_id = Strings::ToUnsignedInt(sep->arg[2]);
		if (!IsValidLiveItemID(c, item_id)) {
			return;
		}

		if (!database.IsLiveItemID(item_id)) {
			c->Message(Chat::White, fmt::format("Item ID {} is outside the configured live item range.", item_id).c_str());
			return;
		}

		auto item = ItemsRepository::FindOne(database, item_id);
		if (!item.id) {
			c->Message(Chat::White, fmt::format("Item ID {} does not exist in the database.", item_id).c_str());
			return;
		}

		const int hp_step     = (arguments >= 3 && sep->IsNumber(3)) ? Strings::ToInt(sep->arg[3]) : 5;
		const int mana_step   = (arguments >= 4 && sep->IsNumber(4)) ? Strings::ToInt(sep->arg[4]) : 5;
		const int damage_step = (arguments >= 5 && sep->IsNumber(5)) ? Strings::ToInt(sep->arg[5]) : 1;

		item.hp = std::max(0, item.hp + hp_step);
		item.mana = std::max(0, item.mana + mana_step);
		item.damage = std::max(0, item.damage + damage_step);
		item.updated = std::time(nullptr);

		if (!ItemsRepository::UpdateOne(database, item)) {
			c->Message(Chat::White, fmt::format("Failed to bump item ID {}.", item_id).c_str());
			return;
		}

		c->Message(
			Chat::White,
			fmt::format(
				"Bumped item ID {} to HP [{}], Mana [{}], Damage [{}]. Wait up to the live item poll interval for held instances to refresh.",
				item_id,
				item.hp,
				item.mana,
				item.damage
			).c_str()
		);
	}
}
