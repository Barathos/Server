	std::string TrimItemForgeText(std::string value)
	{
		while (!value.empty() && std::isspace(static_cast<unsigned char>(value.front()))) {
			value.erase(value.begin());
		}

		while (!value.empty() && std::isspace(static_cast<unsigned char>(value.back()))) {
			value.pop_back();
		}

		return value;
	}

	std::string DecodeItemForgeText(const std::string &value)
	{
		std::string decoded;
		decoded.reserve(std::min<size_t>(value.size(), 60));

		for (const auto raw_ch : value) {
			const auto ch = raw_ch == '_' ? ' ' : raw_ch;
			const bool alpha = (ch >= 'A' && ch <= 'Z') || (ch >= 'a' && ch <= 'z');
			const bool digit = ch >= '0' && ch <= '9';
			const bool separator = ch == ' ' || ch == '-' || ch == '\'';
			if (!alpha && !digit && !separator) {
				continue;
			}

			if (std::isspace(static_cast<unsigned char>(ch))) {
				if (decoded.empty() || decoded.back() == ' ') {
					continue;
				}

				decoded.push_back(' ');
			} else {
				decoded.push_back(ch);
			}

			if (decoded.size() >= 60) {
				break;
			}
		}

		return TrimItemForgeText(decoded);
	}

	bool HasItemForgeNamedArgs(const Seperator *sep)
	{
		for (int index = 2; index <= sep->argnum; ++index) {
			if (std::strchr(sep->arg[index], '=')) {
				return true;
			}
		}

		return false;
	}

	std::string GetItemForgeNamedArg(const Seperator *sep, const std::string &key)
	{
		const auto wanted = Strings::ToLower(key);
		for (int index = 2; index <= sep->argnum; ++index) {
			const std::string token = sep->arg[index];
			const auto separator = token.find('=');
			if (separator == std::string::npos) {
				continue;
			}

			if (Strings::ToLower(token.substr(0, separator)) == wanted) {
				return token.substr(separator + 1);
			}
		}

		return {};
	}

	int GetItemForgeNamedInt(const Seperator *sep, const std::string &key, const int fallback)
	{
		const auto value = GetItemForgeNamedArg(sep, key);
		return value.empty() ? fallback : Strings::ToInt(value);
	}

	std::string SanitizeItemForgeName(const std::string &name)
	{
		auto decoded = DecodeItemForgeText(name);
		if (decoded.empty()) {
			return {};
		}

		for (auto &ch : decoded) {
			if (std::isspace(static_cast<unsigned char>(ch))) {
				ch = '_';
			}
		}

		return decoded;
	}

	std::string ItemForgeDraftBucketKey(Client *c)
	{
		return fmt::format("{}{}", LiveItemForgeDraftBucketPrefix, c->CharacterID());
	}

	bool ParseItemForgeToken(const std::string &token, std::string &key, std::string &value)
	{
		const auto separator = token.find('=');
		if (separator == std::string::npos) {
			return false;
		}

		key = Strings::ToLower(token.substr(0, separator));
		value = token.substr(separator + 1);
		return !key.empty() && !value.empty();
	}

	std::vector<std::pair<std::string, std::string>> ParseItemForgeDraft(const std::string &draft)
	{
		std::vector<std::pair<std::string, std::string>> values;
		const auto tokens = Strings::Split(draft, ' ');
		for (const auto &token : tokens) {
			std::string key;
			std::string value;
			if (ParseItemForgeToken(token, key, value)) {
				values.emplace_back(key, value);
			}
		}

		return values;
	}

	std::string BuildItemForgeDraft(const std::vector<std::pair<std::string, std::string>> &values)
	{
		std::vector<std::string> tokens;
		tokens.reserve(values.size());
		for (const auto &[key, value] : values) {
			if (!key.empty() && !value.empty()) {
				tokens.emplace_back(fmt::format("{}={}", key, value));
			}
		}

		return Strings::Join(tokens, " ");
	}

	void SetItemForgeDraftValue(std::vector<std::pair<std::string, std::string>> &values, const std::string &key, const std::string &value)
	{
		for (auto &[existing_key, existing_value] : values) {
			if (existing_key == key) {
				existing_value = value;
				return;
			}
		}

		values.emplace_back(key, value);
	}

	std::string GetItemForgeDraftValue(const std::vector<std::pair<std::string, std::string>> &values, const std::string &key)
	{
		const auto wanted = Strings::ToLower(key);
		for (const auto &[existing_key, existing_value] : values) {
			if (existing_key == wanted) {
				return existing_value;
			}
		}

		return {};
	}

	int GetItemForgeDraftInt(const std::vector<std::pair<std::string, std::string>> &values, const std::string &key, const int fallback)
	{
		const auto value = GetItemForgeDraftValue(values, key);
		return value.empty() ? fallback : Strings::ToInt(value);
	}

	uint32 BuildSlotMask(const std::initializer_list<int> slots)
	{
		uint32 mask = 0;
		for (const auto slot : slots) {
			mask |= static_cast<uint32>(1u << slot);
		}

		return mask;
	}

	uint32 FindFreeForgedLiveItemID()
	{
		const auto minimum = static_cast<uint32>(std::max(1, RuleI(Items, LiveItemMinID)));
		const auto maximum = static_cast<uint32>(std::max(0, RuleI(Items, LiveItemMaxID)));

		auto start = static_cast<uint32>(Strings::ToUnsignedInt(DataBucket::GetData(&database, LiveItemForgeNextBucket)));
		if (start < minimum) {
			start = minimum;
		}

		for (uint32 item_id = start; item_id <= maximum || maximum == 0; ++item_id) {
			if (maximum && item_id > maximum) {
				break;
			}

			if (database.IsLiveItemID(item_id) && !ItemsRepository::FindOne(database, item_id).id) {
				DataBucket::SetData(&database, LiveItemForgeNextBucket, std::to_string(item_id + 1));
				return item_id;
			}

			if (maximum == 0 && item_id == std::numeric_limits<uint32>::max()) {
				break;
			}
		}

		return 0;
	}

	void ApplyItemForgeType(ItemsRepository::Items &item, const ItemForgeDefinition &definition)
	{
		const auto type = Strings::ToLower(definition.item_type);
		if (type == "augment" || type == "aug") {
			item.itemtype = EQ::item::ItemTypeAugmentation;
			item.slots = 0;
			item.icon = 646;
			item.augtype = 7;
			item.augslot1type = 0;
			item.augslot1visible = 0;
			item.augslot2type = 0;
			item.augslot2visible = 0;
			item.damage = 0;
			item.delay = 0;
			item.haste = 0;
			item.ac = std::max(item.ac, 3);
			return;
		}

		if (type == "armor") {
			item.itemtype = EQ::item::ItemTypeArmor;
			item.slots = BuildSlotMask({EQ::invslot::slotChest});
			item.icon = 538;
			item.damage = 0;
			item.delay = 0;
			item.haste = 0;
			item.ac = std::max(item.ac, 10);
			return;
		}

		if (type == "jewelry") {
			item.itemtype = EQ::item::ItemTypeJewelry;
			item.slots = BuildSlotMask({EQ::invslot::slotFinger1, EQ::invslot::slotFinger2});
			item.icon = 674;
			item.damage = 0;
			item.delay = 0;
			item.haste = 0;
			item.ac = std::max(0, item.ac / 2);
			return;
		}

		if (type == "charm") {
			item.itemtype = EQ::item::ItemTypeCharm;
			item.slots = BuildSlotMask({EQ::invslot::slotCharm});
			item.icon = 1123;
			item.damage = 0;
			item.delay = 0;
			item.haste = 0;
			return;
		}

		if (type == "shield") {
			item.itemtype = EQ::item::ItemTypeShield;
			item.slots = BuildSlotMask({EQ::invslot::slotSecondary});
			item.icon = 535;
			item.damage = 0;
			item.delay = 0;
			item.haste = 0;
			item.ac = std::max(item.ac, 15);
			return;
		}

		item.itemtype = EQ::item::ItemType1HSlash;
		item.slots = BuildSlotMask({EQ::invslot::slotPrimary, EQ::invslot::slotSecondary});
		item.icon = 519;
	}

