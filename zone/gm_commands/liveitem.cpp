	bool IsValidLiveItemID(Client *c, const uint32 item_id)
	{
		if (!item_id || item_id > static_cast<uint32>(std::numeric_limits<int32>::max())) {
			c->Message(Chat::White, "Enter an item ID from 1 to 2147483647.");
			return false;
		}

		return true;
	}

	void SendItemSummary(Client *c, const EQ::ItemData *item)
	{
		if (!item) {
			c->Message(Chat::White, "Resolved Item: not found.");
			return;
		}

		c->Message(
			Chat::White,
			fmt::format(
				"Resolved Item: [{}] {} | HP [{}] Mana [{}] Damage [{}] Delay [{}] Haste [{}] Proc [{}]",
				item->ID,
				item->Name,
				item->HP,
				item->Mana,
				item->Damage,
				item->Delay,
				item->Haste,
				item->Proc.Effect
			).c_str()
		);
	}

	void SummonLiveItem(Client *c, const uint32 item_id, int16 charges)
	{
		const auto *item = database.GetItem(item_id);
		if (!item) {
			c->Message(Chat::White, fmt::format("Item ID {} does not exist.", item_id).c_str());
			return;
		}

		if (item->MinStatus > c->Admin()) {
			c->Message(
				Chat::White,
				fmt::format(
					"Insufficient status to summon this item, current status is {}, required status is {}.",
					c->Admin(),
					item->MinStatus
				).c_str()
			);
			return;
		}

		c->SummonItem(item_id, charges);

		const auto *new_item = database.CreateItem(item_id, charges);
		EQ::SayLinkEngine linker;
		linker.SetLinkType(EQ::saylink::SayLinkItemInst);
		linker.SetItemInst(new_item);

		c->Message(Chat::White, fmt::format("You have summoned {}.", linker.GenerateLink()).c_str());
		safe_delete(new_item);
	}

	bool UpsertLiveItemClone(Client *c, const uint32 target_id, const uint32 source_id)
	{
		auto source = ItemsRepository::FindOne(database, source_id);
		if (!source.id) {
			c->Message(Chat::White, fmt::format("Source item ID {} does not exist.", source_id).c_str());
			return false;
		}

		const bool replacing = ItemsRepository::FindOne(database, target_id).id != 0;

		source.id        = target_id;
		source.minstatus = 0;
		source.Name      = fmt::format("Live Test Item {}", target_id);
		source.lore      = fmt::format("A live item cloned from {}", source_id);
		source.comment   = "Generated by #liveitem clone";
		source.hp += 25;
		source.mana += 25;
		source.haste = std::max(source.haste, 5);
		source.damage = std::max<int32>(source.damage + 1, 1);
		source.delay = std::max<int32>(source.delay, 20);
		source.updated = std::time(nullptr);

		if (replacing) {
			if (!ItemsRepository::UpdateOne(database, source)) {
				c->Message(Chat::White, fmt::format("Failed to update live item ID {}.", target_id).c_str());
				return false;
			}
		} else {
			ItemsRepository::InsertOne(database, source);
			if (!ItemsRepository::FindOne(database, target_id).id) {
				c->Message(Chat::White, fmt::format("Failed to insert live item ID {}.", target_id).c_str());
				return false;
			}
		}

		database.ClearLiveItemCache(target_id);
		c->Message(
			Chat::White,
			fmt::format(
				"{} live item ID {} from source item ID {}.",
				replacing ? "Updated" : "Created",
				target_id,
				source_id
			).c_str()
		);

		return true;
	}

